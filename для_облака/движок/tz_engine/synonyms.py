def detect_category(name: str, ktru: str = "", okpd2: str = "") -> str | None:
    n = norm_name(name)
    for pat, cat in NAME_CATEGORY:
        if re.search(pat, n):
            return cat
    code = ktru or okpd2 or ""
    if re.search(r"телефон", n) and code.startswith("26.30.23"):
        return "телефон"     # обычный (не IP) аппарат — в демо-каталоге таких нет
    if code.startswith("26.30.23") and not re.search(r"телефон", n):
        return None          # трансиверы, SFP и т. п.
    for prefix, cat in CODE_CATEGORY:
        if code.startswith(prefix):
            return cat
    return None
