@dataclass
class Key:
    key: str
    header: str                 # заголовок столбца в каталоге
    kind: str                   # num | text | bool | res
    patterns: list[str]
    cats: set[str] | None = None
    exclude: list[str] = field(default_factory=list)
    unit: str = ""              # единица столбца каталога

    def matches(self, name: str, cat: str | None) -> bool:
        if self.cats is not None and cat not in self.cats:
            return False
        if any(re.search(e, name) for e in self.exclude):
            return False
        return any(re.search(p, name) for p in self.patterns)


