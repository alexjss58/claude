def norm_name(name: str) -> str:
    n = (name or "").lower().replace("ё", "е").replace(" ", " ")
    n = re.sub(r"\s+", " ", n).strip()
    return n


def is_kit(name: str) -> bool:
    n = norm_name(name)
    return any(re.search(p, n) for p in KIT_PATTERNS)


def map_key(name: str, category: str | None) -> Key | None:
    """Канонический ключ характеристики (или None, если в каталоге такой нет)."""
    n = norm_name(name)
    if is_kit(n):
        return None
    for k in KEYS:
        if k.matches(n, category):
            return k
    return None


