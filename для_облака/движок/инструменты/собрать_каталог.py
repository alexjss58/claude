def build() -> pd.DataFrame:
    used = []
    for k in KEYS:
        if any(k.key in r for r in ROWS) and k.header not in used:
            used.append(k.header)
    head = {k.key: k.header for k in KEYS}
    recs = []
    for r in ROWS:
        rec = {"Артикул (демо)": r["sku"], "Категория": r["cat"], "Производитель": r["vendor"], "Модель": r["model"],
               "Конфигурация / примечание": r.get("config", ""), "Реестр (по данным производителя)": r.get("registry", ""),
               "ОКПД2 (типовой для категории)": OKPD.get(r["cat"], ""), "Источник (URL)": r["url"],
               "Надёжность": OK_SITE, "Дата проверки": CHECKED}
        for key, val in r.items():
            if key in head:
                rec[head[key]] = val
        recs.append(rec)
    df = pd.DataFrame(recs, columns=META + used)
    return df


