regs = []
for t in R.split('|'):
    c, n, fo = t.split(' ')
    regs.append({'код': int(c), 'название': n.replace('_', ' '), 'фо': fo})
byname = {r['название']: r for r in regs}
alias = {'Татарстан респ.': 'Татарстан', 'Саха (Якутия) респ.': 'Саха (Якутия)', 'Адыгея респ.': 'Адыгея', 'Дагестан респ.': 'Дагестан',
         'Хакасия респ.': 'Хакасия', 'Удмуртская респ.': 'Удмуртия', 'Ямало-Ненецкий автономный округ': 'Ямало-Ненецкий автономный округ'}
def region(name):
    name = alias.get(name, name)
    return byname.get(name)

def niche(codes, subject):
    s = subject.lower()
    if re.search(r'реактив|химическ', s): return 'Лабораторные реактивы'
    c = codes[0] if codes else ''
    if c.startswith('26.51'): return 'Измерительные приборы'
    if c.startswith('26.40') or re.search(r'звук|аудио|микрофон|проектор', s): return 'Аудио- и видеотехника'
    if c.startswith('26.30') and not c.startswith('26.30.50') or re.search(r'коммутатор|телефон|маршрутизатор|связ', s): return 'Связь и сети'
    return 'Компьютеры и оргтехника'

def nice(s):
    s = re.sub(r'\s+', ' ', s).strip()
    if not s.isupper(): return s
    s = s.lower()
    return re.sub(r'(^|["«(]\s?)([а-яa-z])', lambda m: m[1] + m[2].upper(), s)

items = []
for f in sorted(glob.glob(os.path.join(src, '0*.json'))):
    d = json.load(open(f, encoding='utf-8'))
    z = d['закупка']
    m = re.match(r'(\d\d)\.(\d\d)\.(\d{4})', z.get('дата_окончания') or '')
    if not m: continue
    end = f'{m[3]}-{m[2]}-{m[1]}T09:00:00'
    if end < '2026-11-04': continue
    r = region(z.get('регион') or '')
    pos = []
    for p in d['позиции']:
        pos.append({'№': p['№'], 'наименование': p['наименование'], 'окпд2': p['окпд2'], 'ктру': p.get('ктру', ''),
                    'количество': p['количество'], 'единица': p['единица'], 'цена_за_ед': None,
                    'характеристики': [{k: c[k] for k in ('имя', 'условие', 'значение', 'единица')} for c in p['характеристики']]})
    codes = [p['окпд2'] for p in pos]
    flags = []
    if re.search(r'(?<![А-Яа-я])(HP|Panasonic|Cisco|Huawei|Kyocera|Xerox|Canon|Brother)(?![A-Za-z])', z['предмет']): flags.append('бренд в названии')
    typ = 'работы/услуги' if re.search(r'установк|монтаж|ввод в эксплуатацию', z['предмет'], re.I) else 'поставка'
    if typ != 'поставка': flags.append('работы/услуги')
    t = {'номер': z['номер'], 'закон': z['закон'], 'способ': z['способ'], 'предмет': re.sub(r'\s+', ' ', z['предмет']).strip(),
         'заказчик': nice(z['заказчик']),
         'инн_заказчика': z.get('инн_заказчика', ''), 'регион_код': r['код'] if r else None, 'регион': r['название'] if r else '',
         'нмц': z['нмц'], 'обеспечение_заявки_проц': None, 'обеспечение_контракта_проц': None,
         'опубликовано': '2026-11-03', 'окончание_подачи': end, 'окпд2': sorted(set(codes)), 'ктру': sorted(set(p['ктру'] for p in pos if p['ктру'])),
         'ниша': niche(codes, z['предмет']), 'тип': typ, 'флаги': flags, 'ссылка': z['ссылка'], 'позиции': pos}
    items.append(t)
# Чтобы показать режим «ТЗ в документах» (часто 223-ФЗ), у одной закупки позиции убраны намеренно.
for t in items:
    if 'телефон' in t['предмет'].lower() and 'Panasonic' in t['предмет']:
        t['позиции'] = None
        t['закон'] = t['закон']
items = items[:24]
snap = {'пример': True, 'снято': '2026-11-03T15:00:00+03:00',
        'источник': 'ПРИМЕР: реальные закупки из демо-выхода движка (движок/демо_выход), без цен за единицу; у одной закупки позиции убраны намеренно',
        'ниши': ['Компьютеры и оргтехника', 'Связь и сети', 'Аудио- и видеотехника', 'Измерительные приборы', 'Лабораторные реактивы'],
        'тендеры': items}
json.dump(snap, open(os.path.join(root, 'data', '_пример_снимка.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
json.dump(regs, open(os.path.join(root, 'data', '_пример_регионов.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
print(len(items), 'закупок', len(regs), 'регионов')
from collections import Counter
print(Counter(t['ниша'] for t in items), Counter(t['тип'] for t in items))
