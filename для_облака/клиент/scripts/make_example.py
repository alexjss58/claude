#!/usr/bin/env python3
"""Собирает data/_пример_снимка.json и data/_пример_регионов.json из демо-выхода движка (формат G -> F).
Запуск: python3 scripts/make_example.py. Это ПРИМЕР: реальный снимок кладёт другой агент в data/снимок.json."""
