/** Что сделать поставщику — по режиму (и закону) */
export function whatToDo(info: NatInfo, law: string): string {
  const is223 = law.includes('223');
  const share = is223 && info.rule?.доля ? ` Если заказчик — госкомпания или её дочерняя, у него есть минимальная доля российского (по таблице: ${info.rule.доля}).` : '';
  switch (info.mode) {
    case 'запрет':
      return 'Иностранный товар не подавать. Нужен товар с номером записи в реестре российской промышленной продукции (ГИСП), действующей на дату подачи. Нет такого товара в ассортименте — искать у дистрибьютора или пропустить закупку.';
    case 'ограничение':
      return `Иностранный товар проходит, только если нет допущенной заявки с российским. Безопаснее предлагать товар с номером записи в реестре российской промышленной продукции (ГИСП): запись должна относиться к вашей модели и действовать на дату подачи. Если записи нет, подавать можно, но с риском отклонения.${share}`;
    case 'преимущество':
      return 'Российскому товару при сравнении цен дают условное снижение на 15%. Если у вас иностранный товар, учтите это в цене; если российский, подтвердите происхождение номером записи в реестре.';
    default:
      return 'Открыть извещение и найти, какая мера применена (запрет, ограничение или преимущество). Сверить код ОКПД2 позиции с приложениями № 1 и № 2 постановления № 1875. Если кода в них нет, действует преимущество 15% для российского товара.';
  }
}

/** Сколько позиций в каждом режиме */
export function modeCounts(codes: string[]): Record<NatMode, number> {
  const c: Record<NatMode, number> = { запрет: 0, ограничение: 0, преимущество: 0, неизвестно: 0 };
  for (const code of codes) c[natInfo(code).mode]++;
  return c;
}
