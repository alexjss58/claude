export interface NatInfo {
  mode: NatMode;
  rule: NatRule | null;
}

export function natInfo(okpd2: string): NatInfo {
  const code = (okpd2 || '').trim();
  if (!code) return { mode: 'неизвестно', rule: null };
  let best: NatRule | null = null;
  for (const r of NAT_RULES) {
    if (code.startsWith(r.prefix) && (!best || r.prefix.length > best.prefix.length)) best = r;
  }
  return best ? { mode: best.mode, rule: best } : { mode: 'неизвестно', rule: null };
}

