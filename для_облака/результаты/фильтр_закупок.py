# -*- coding: utf-8 -*-
"""
Прототип фильтра закупок по НАЗВАНИЮ (блок E проекта «Тендер под ключ»).

Что делает
----------
Функция `классифицировать(название)` читает только название закупки и возвращает словарь:

    {
      'тип':        'поставка' | 'работы_услуги' | 'смешанная',
      'под_своего': True | False,      # есть признаки закупки «под конкретного поставщика»
      'признаки':   [список строк]     # какие правила сработали (для демо-сайта и движка)
    }

Зачем: «чистая поставка товара» — наш целевой тип закупок (подбор товара под техзадание,
цена, заявка). «Работы/услуги» и «смешанные» (поставка + монтаж) требуют другого процесса,
их движок показывает отдельно. «Под своего» — предупреждение клиенту: шанс победить ниже.

Как устроено (правила, без ИИ-модели; всё читаемо и правится руками)
-------------------------------------------------------------------
1. Тип:
   * ищем слова-маркеры работ/услуг (монтаж, ремонт, обслуживание, аренда, оказание услуг…);
     маркер игнорируется, если стоит после «для/в целях/к/при» («запчасти ДЛЯ ремонта» — это товар);
   * ищем слова-маркеры поставки (поставка, закупка, приобретение, покупка);
   * только работы -> 'работы_услуги'; и то и другое -> 'смешанная'; иначе -> 'поставка'.
     Если в названии нет ни того ни другого («Журналы», «Блокнот»), считаем это названием
     товара = 'поставка' и добавляем признак 'нет_глагола'.
2. Под своего (оценка ТОЛЬКО по названию, поэтому только подсказка, не вердикт):
   * бренд или модель в названии (латинское слово-бренд, код модели вроде BSQ-36HN8,
     название в «ёлочках» из словаря брендов) и НЕТ слов «или эквивалент/аналог»;
   * «узкие характеристики»: 4 и более числовых параметров с единицами (мм, Вт, ГБ…) без эквивалента;
   * «только оригинал / только новый» без слова «аналог».
   Исключение: запчасти и расходники к технике («запчасти для автобусов ЛИАЗ-5292»,
   «картридж для принтера HP») — марка техники здесь описывает совместимость, это признак
   'бренд_совместимость' и под_своего остаётся False.
3. Номера закупок («№ 223/045-2026», «440-ЗК(ЭЛ)», «Лот 2») и название заказчика после
   «для нужд …» отрезаются до поиска брендов, чтобы их не принять за модель.

Ограничения: по названию нельзя узнать содержимое техзадания; «Поставка товара» может скрывать
что угодно. Не юридическая консультация: признак «под своего» — не доказательство нарушения.

Запуск тестов:   python3 -m pytest фильтр_закупок.py -q
Быстрая проверка: python3 фильтр_закупок.py "Поставка и установка сплит-систем Ballu BSQ-36HN8"
"""
