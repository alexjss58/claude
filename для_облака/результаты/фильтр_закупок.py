def _очистить(название: str) -> str:
    """Убирает номера закупок, годы, лоты и хвост «для нужд <заказчик>»."""
    t = ' ' + (название or '').replace('\xa0', ' ').replace('_x000D_', ' ').replace('_x000d_', ' ') + ' '
    t = re.sub(r'услуг\w*\s+по\s+(?=поставк)', '', t, flags=re.I)   # «услуги по поставке» = поставка
    t = _ХВОСТ_ЗАКАЗЧИК.sub('', t)
    for r in _ШУМ:
        t = r.sub(' ', t)
    return re.sub(r'\s+', ' ', t).strip()


def _тип_работ(низ: str):
    """Возвращает список найденных маркеров работ (без случаев «для ремонта»)."""
    найдено = []
    for шаблон in _РАБОТЫ:
        for m in re.finditer(r'(?<![а-яa-z\-])' + шаблон, низ):
            до = низ[:m.start()]
            предмет = re.search(r'(?:поставк\w*|закупк\w*|приобретени\w*)\s+$', до[-25:]) and m.group(0).startswith('установк')
            if предмет:
                continue                          # «Поставка установки спектрометрической» — это предмет-оборудование
            приложение = _ПРИЛОЖЕНИЕ.search(до[-4:]) and re.match(r'установк|монтаж|пусконал|пуско|наладк|сборк|демонтаж', m.group(0))
            if not приложение and _ЦЕЛЬ_ПЕРЕД.search(до[-45:]) or re.search(r'в\s+целях|с\s+целью', до):
                continue                        # «запчасти ДЛЯ ремонта», «в целях модернизации» -> цель, не предмет
            найдено.append(m.group(0).strip())
    return найдено


def _бренды(чист: str):
    """Ищет бренды и модели в очищенном названии. Возвращает (бренды, модели, позиции)."""
    низ = чист.lower()
    бренды, позиции = [], []
    for m in _ЛАТ_СЛОВО.finditer(чист):
        w = m.group(0)
        if w.lower() in _НЕ_БРЕНД or w.isupper() and len(w) <= 4 and w.lower() not in _БРЕНДЫ:
            continue                       # аббревиатуры (LED, USB, ИБП) не считаем брендом
        бренды.append(w); позиции.append(m.start())
    for m in _ЁЛОЧКИ.finditer(чист):
        внутри = m.group(1).strip()
        if внутри.lower() in _БРЕНДЫ:
            бренды.append(внутри); позиции.append(m.start())
    for b in _БРЕНДЫ:                       # кириллические бренды и марки техники из словаря
        if re.search(r'[а-я]', b):
            m = re.search(r'(?<![а-я])' + re.escape(b) + r'(?![а-я])', низ)
            if m:
                бренды.append(b); позиции.append(m.start())
    модели, мпоз = [], []
    for m in _МОДЕЛЬ.finditer(чист):
        w = m.group(0)
        if re.fullmatch(r'\d+[\-/]\d+', w) or re.fullmatch(r'[A-Za-zА-Яа-я]{1,2}\d{1,2}', w) and False:
            continue
        # отсеиваем размеры вида «50х70», «3х2.5» и единицы «220в»
        if re.fullmatch(r'\d+[xх*]\d+(?:[xх*]\d+)?\w{0,3}', w, re.I) or re.fullmatch(r'\d+(?:[.,]\d+)?[а-яa-z]{1,4}', w, re.I):
            continue
        цифр = sum(ch.isdigit() for ch in w)
        if цифр < 2 or w[0].isdigit() or w.count('-') >= 2 or w.count('/') >= 1 and цифр > 4:
            continue          # одна цифра («ТЭЦ-2»), «2-мя», номера заявок («ЗНЗн-24-331»)
        if re.fullmatch(r'(?:Ду|ДУ|Дн|DN|PN|Dn|А|Е|С|Б|В|M|М|Т|ТО|СО)\d{1,3}', w) and not re.search(r'-', w):
            continue          # типоразмеры: Ду15, А4, Е65, M8
        if 'x000' in w.lower() or 'rts' in w.lower():
            continue
        модели.append(w); мпоз.append(m.start())
    return бренды, позиции, модели, мпоз


def классифицировать(название: str) -> dict:
    """Главная функция. См. описание модуля. Пустое название -> 'поставка' с признаком 'пустое_название'."""
    признаки = []
    if not название or not str(название).strip():
        return {'тип': 'поставка', 'под_своего': False, 'признаки': ['пустое_название']}
    название = str(название)
    низ_полн = название.lower()
    чист = _очистить(название)
    низ = чист.lower()

    # ---------- 1. тип закупки
    работы = _тип_работ(низ)
    есть_поставка = bool(_ПОСТАВКА.search(низ))
    if работы and есть_поставка:
        тип = 'смешанная'
    elif работы:
        тип = 'работы_услуги'
    else:
        тип = 'поставка'
        if not есть_поставка:
            признаки.append('нет_глагола')
    if работы:
        признаки += ['работы:' + w for w in dict.fromkeys(работы)][:4]
    if _ОБЩЕЕ.match(низ) or re.fullmatch(r'(?:поставка|закупка)\s+товара?\s*', низ):
        признаки.append('общее_название')

    # ---------- 2. под своего (только для названий, где что-то поставляется)
    экв = bool(_ЭКВИВАЛЕНТ.search(низ_полн))
    бренды, bpos, модели, mpos = _бренды(чист)
    # совместимость: «запчасти для автобусов ЛИАЗ-5292» — марка описывает чужую технику
    совм = bool(_СОВМЕСТИМОСТЬ.search(низ))

    def в_совместимости(pos):
        # в запчастях/расходниках марка почти всегда описывает технику, к которой деталь подходит;
        # «лампа ДЛЯ микроскопа Leica» — тоже совместимость, даже если слово «лампа» не в словаре
        return совм or bool(_ПРЕДЛОГ_СОВМ.search(низ[:pos][-50:]))

    найденные = []
    for w, p in list(zip(бренды, bpos)) + list(zip(модели, mpos)):
        if в_совместимости(p):
            continue
        найденные.append(w)
    только_совм = (бренды or модели) and not найденные
    if только_совм:
        признаки.append('бренд_совместимость')
    под = False
    if найденные:
        if экв:
            признаки.append('бренд_с_эквивалентом')
        else:
            под = True
            признаки.append('бренд_или_модель:' + ', '.join(dict.fromkeys(найденные))[:60])
            признаки.append('нет_или_эквивалент')
    характеристики = _ХАР.findall(чист)
    if len(характеристики) >= 4 and not экв:
        под = True
        признаки.append('узкие_характеристики:%d' % len(характеристики))
    if _ОРИГИНАЛ.search(низ_полн) and not экв:
        под = True
        признаки.append('только_оригинал')
    if тип == 'работы_услуги':
        # для чистых работ вопрос «под своего по товару» не ставим
        под = False
        признаки = [x for x in признаки if not x.startswith(('бренд_или_модель', 'нет_или_эквивалент', 'узкие', 'только'))]
    return {'тип': тип, 'под_своего': под, 'признаки': признаки}


