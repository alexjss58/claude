def fmt_pct(x):
    if x is None:
        return None
    return str(int(x)) if float(x).is_integer() else f"{x:.1f}".replace(".", ",")


def fmt_mln(s):
    """Сумма «понятно»: от 10 млн — целые миллионы, меньше — один знак после запятой."""
    m = s / 1e6
    if m >= 10:
        return str(int(round(m)))
    v = round(m, 1)
    return str(int(v)) if float(v).is_integer() else f"{v:.1f}".replace(".", ",")


def fmt_rub(s):
    return f"{s:,}".replace(",", " ") + " ₽"


def letter_type(red):
    """Тип по среднему снижению цены (правила блока B)."""
    if red is None:
        return "а (по умолчанию)", "а"
    if red <= 7:
        return "а", "а"
    if red > 25:
        return "б", "б"
    if red <= 16:
        return "а (пограничный)", "а"
    return "б (пограничный)", "б"


def fio_to_io(fio):
    """«Фамилия Имя Отчество (...)» -> «Имя Отчество»."""
    core = fio.split("(")[0].strip()
    parts = core.split()
    return f"{parts[1]} {parts[2]}" if len(parts) >= 3 else None


def ip_io(company):
    """«ИП ПИГАЛЕВА ЮЛИЯ. ЕВГЕНЬЕВНА.» -> «Юлия Евгеньевна»."""
    toks = [t for t in re.split(r"[\s.]+", company.replace("ИП", "", 1)) if t]
    return f"{toks[1].capitalize()} {toks[2].capitalize()}"


def address(rec):
    """Обращение по правилам: ИП — имя и отчество из названия; ООО/АО — имя и отчество
    руководителя, если он известен и почта не общая; иначе «Здравствуйте!»."""
    comp, head, mail = rec["Компания"], rec["Руководитель"], rec["Почта"]
    if comp.startswith("ИП "):
        io = ip_io(comp)
        return io, "ИП — имя и отчество из названия"
    if not head:
        return None, "руководитель неизвестен"
    if "расход" in head:
        return None, "данные о руководителе в справочниках расходятся"
    if not mail:
        io = fio_to_io(head)
        return io, ("руководитель известен (из справочника), почту возьмёте в Тендерплане; "
                    "если адрес окажется общим (info@, tender@, zakupki@) — замените на «Здравствуйте!»")
    local = mail.split("@")[0]
    if local == "ivan":
        return None, ("ящик ivan@ — личный, но не руководителя (руководитель — женщина); "
                      "имя по адресу не угадываем")
    return None, f"почта общая ({local}@)"


def niche_link_map():
    """Ссылки на карточки Тендерплана и надёжность почты из поставщики_75.xlsx."""
    wb = openpyxl.load_workbook(SUPPL, data_only=True)
    best = {}
    ws = wb["Лучшие 30"]
    hdr = [c.value for c in ws[1]]
    for r in ws.iter_rows(min_row=2, values_only=True):
        d = dict(zip(hdr, r))
        best[d["Компания"]] = d
    cards = {}
    for sh in NICHES:
        ws = wb[sh]
        hdr = [c.value for c in ws[1]]
        for r in ws.iter_rows(min_row=2, values_only=True):
            d = dict(zip(hdr, r))
            cards[d["Поставщик"]] = d
    return best, cards


def base_template():
    """Основа письма — дословно из ЗАДАНИЕ.md (блок B)."""
    txt = TASK.read_text(encoding="utf-8")
    m = re.search(r"«(Здравствуйте, \[Имя\]!.*?@alex_wp)»", txt, re.S)
    if not m:
        sys.exit("Не нашёл основу письма в ЗАДАНИЕ.md")
    return m.group(1)


def fill_base(base, greet_io, line, otrasl):
    g = f"Здравствуйте, {greet_io}!" if greet_io else "Здравствуйте!"
    return (base.replace("Здравствуйте, [Имя]!", g)
                .replace("[Персональная строка.]", line)
                .replace("[отрасль]", otrasl))


def paragraphs(flat, line):
    """Разбивает письмо на абзацы для чтения (текст при этом не меняется)."""
    out = flat
    for marker in ["Меня зовут Алексей.", line, "Сейчас мы разговариваем",
                   "Удобно созвониться", SIGNATURE]:
        out = out.replace(" " + marker, "\n\n" + marker, 1)
    return out


def site_url(s):
    if not s:
        return None
    return s if s.startswith("http") else "https://" + s


