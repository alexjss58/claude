FORBIDDEN = [
    "разбор", "госзакуп", "госзаказ", "[", "]", "None", "nan", "срочн", "успейте", "только сегодня",
    "последний шанс", "гарантир", "гарантия победы", "выиграете", "победу обеспеч", "уникальн", "лучш",
    "100%", "данный", "осуществ", "в рамках", "является", "в целях", "посредством", "вышеуказ",
    "настоящим", "в связи с", "в соответствии", "на сегодняшний день", "предоставлени",
    "под своего", "свои закупки", "своих закупк", "под вас", "  ", " ,", " .", ",,",
]
SUBJ_FORBIDDEN = ["!", "бесплатн", "выгод", "скидк", "предложени", "ИИ"]


def sentences(text):
    parts = re.split(r"(?<=[.!?])\s+", text.strip())
    return [p for p in parts if p]


def strip_fixed(text):
    t = text.replace(SIGNATURE, " ")
    for frag in ["80–90%", "20–30", "18:00", "@alex_wp"]:
        t = t.replace(frag, " ")
    return t


def check_numbers(text, rec, words):
    """Все числа в тексте — только из входа: участия, победы, снижение, сумма (округлённая)."""
    errs = []
    t = strip_fixed(text)
    part, wins = rec["Участий за квартал"], rec["Побед"]
    red, summ = rec["Среднее снижение, %"], rec["Контрактов на сумму, ₽"]
    pct, mln = fmt_pct(red), fmt_mln(summ)
    for v in re.findall(r"(\d+(?:,\d+)?)\s?%", t):
        if v != pct:
            errs.append(f"процент {v}% ≠ {pct}%")
    t = re.sub(r"\d+(?:,\d+)?\s?%", " ", t)
    for v in re.findall(r"(\d+(?:,\d+)?) млн ₽", t):
        if v != mln:
            errs.append(f"сумма {v} млн ₽ ≠ {mln} млн ₽")
    t = re.sub(r"\d+(?:,\d+)? млн ₽", " ", t)
    for v in re.findall(r"\d+(?:,\d+)?", t):
        if v not in {str(part), str(wins)}:
            errs.append(f"лишнее число {v}")
    for a, b in re.findall(r"(\d+)\s+(?:\w+\s+)?(?:из|в)\s+(\d+)\b", t):
        if (int(a), int(b)) != (wins, part):
            errs.append(f"пара {a} из/в {b} ≠ {wins} из {part}")
    for v in re.findall(r"\bвсе (\d+)", t):
        if not (int(v) == wins == part):
            errs.append(f"«все {v}» не совпадает")
    for w, (lo, hi) in WORD_RANGES.items():
        if w in text and not (red is not None and lo <= red <= hi):
            errs.append(f"словесная оценка «{w}» не подходит к снижению {red}")
    return errs


def self_check(rows, base):
    log, errors = [], []

    def err(n, m):
        errors.append(f"№{n}: {m}")

    data = json.loads(IN_JSON.read_text(encoding="utf-8"))
    if len(rows) != 30:
        errors.append(f"строк {len(rows)} вместо 30")
    # сверка входа с поставщики_75.xlsx
    best, _ = niche_link_map()
    for rec in data:
        b = best.get(rec["Компания"])
        if not b:
            errors.append(f"{rec['Компания']} нет в «Лучшие 30»")
            continue
        for k in ["Участий за квартал", "Побед", "Среднее снижение, %", "Контрактов на сумму, ₽"]:
            if b[k] != rec[k]:
                errors.append(f"{rec['Компания']}: {k} в xlsx {b[k]} ≠ json {rec[k]}")
    log.append("1. Вход: 30 компаний, числа JSON совпадают с листом «Лучшие 30» поставщики_75.xlsx.")

    sig_ok = 0
    for r in rows:
        n, rec = r["n"], r["rec"]
        texts = {"тема": r["subject"], "письмо": r["letter"], "мессенджер": r["msg"], "напоминание": r["remind"]}
        # запреты
        for name, tx in texts.items():
            low = tx.lower()
            for f in FORBIDDEN:
                if f.lower() in low if f not in ("[", "]", "  ", " ,", " .", ",,", "None", "nan") else f in tx:
                    err(n, f"{name}: запрещённое «{f}»")
        for f in SUBJ_FORBIDDEN:
            if f.lower() in r["subject"].lower() if f != "ИИ" else f in r["subject"]:
                err(n, f"тема: «{f}»")
        if re.search(r"\b[А-ЯЁA-Z]{2,}\b", r["subject"]):
            err(n, "тема: слово капсом")
        if len(r["subject"]) > 60:
            err(n, "тема длиннее 60 знаков")
        # основа письма сохранена дословно
        if r["letter"].replace("\n\n", " ") != fill_base(base, r["io"], r["line"], NICHES[rec["Ниша"]]["otrasl"]):
            err(n, "письмо не совпадает с основой")
        if r["letter"].endswith(SIGNATURE) and r["letter"].count(SIGNATURE) == 1:
            sig_ok += 1
        else:
            err(n, "подпись")
        # длина частей
        k = len(sentences(r["line"]))
        if not 1 <= k <= 2:
            err(n, f"персональная строка: {k} предложений")
        k = len(sentences(r["msg"]))
        if not 2 <= k <= 4:
            err(n, f"мессенджер: {k} предложений")
        k = len(sentences(r["remind"]))
        if not 2 <= k <= 3:
            err(n, f"напоминание: {k} предложений")
        # числа
        for name in ["письмо", "мессенджер", "напоминание"]:
            for e in check_numbers(texts[name], rec, r["words"]):
                err(n, f"{name}: {e}")
        if str(rec["Участий за квартал"]) not in r["line"]:
            err(n, "в персональной строке нет числа участий")
        # обращение
        if r["io"]:
            src = rec["Компания"] if rec["Компания"].startswith("ИП ") else (rec["Руководитель"] or "")
            for part in r["io"].split():
                if part.lower() not in src.lower():
                    err(n, f"имя «{part}» не из файла")
            if rec["Почта"] and not rec["Компания"].startswith("ИП "):
                err(n, "обращение по имени при общей почте")
        else:
            if not r["letter"].startswith("Здравствуйте!\n"):
                err(n, "обращение без имени оформлено неверно")
        # отрасль по нише
        if f"с поставщиками {NICHES[rec['Ниша']]['otrasl']}," not in r["letter"]:
            err(n, "отрасль")
        # тип
        if r["type"] != letter_type(rec["Среднее снижение, %"])[0]:
            err(n, "тип")
        # кому
        if not rec["Почта"] and "Тендерплан" not in r["to"]:
            err(n, "нет пометки «почту взять в Тендерплане»")
    log.append("2. Запреты («разбор», «госзакуп», «госзаказ», «[», «]», None, давление, превосходные степени, "
               "канцелярит, намёки на «закупки под своего», двойные пробелы) — проверены в теме, письме, "
               "мессенджере и напоминании.")
    log.append(f"3. Основа письма: текст каждого письма совпадает с основой из ЗАДАНИЕ.md после подстановки "
               f"[Имя], [Персональная строка], [отрасль]; подпись в конце — {sig_ok} из 30.")
    log.append("4. Числа: каждое число в письме, мессенджере и напоминании — только участия, победы, снижение "
               "(в формате файла), сумма (округлена по правилу); пары «N из M» и «все N» совпадают с входом; "
               "словесные оценки («почти наполовину», «на треть» и т. п.) соответствуют снижению.")
    log.append("5. Длины: персональная строка 1–2 предложения, мессенджер 2–4, напоминание 2–3; тема ≤ 60 знаков, "
               "без капса, восклицаний и слов «бесплатно»/«выгода».")
    log.append("6. Обращение: имя только у ИП (из названия) и ООО без общей почты; каждое имя есть в исходном поле.")

    # разнообразие персональных строк
    lines = [r["line"] for r in rows]
    if len(set(lines)) != len(lines):
        errors.append("есть одинаковые персональные строки")
    shingles = Counter()
    for ln in lines:
        w = re.findall(r"\w+", ln.lower())
        shingles.update({" ".join(w[i:i + 5]) for i in range(len(w) - 4)})
    common = [(s, c) for s, c in shingles.most_common() if c >= 4]
    log.append("7. Разнообразие: все 30 персональных строк разные; 5-словные фразы, которые повторяются "
               f"в 4 и более строках: {len(common)}" + (": " + "; ".join(f"«{s}» ×{c}" for s, c in common) if common else "."))
    if any(c >= 6 for _, c in common):
        errors.append("слишком частая повторяющаяся фраза: " + str(common[:3]))
    openers = Counter(" ".join(re.findall(r"\w+", ln)[:2]) for ln in lines)
    log.append("   Самые частые начала строк: " + ", ".join(f"«{k}» ×{v}" for k, v in openers.most_common(4)) + ".")

    # перечитываем готовые файлы
    wb = openpyxl.load_workbook(OUT_XLSX)
    if wb.sheetnames != ["Письма", "Как отправлять"]:
        errors.append(f"листы xlsx: {wb.sheetnames}")
    ws = wb["Письма"]
    hdr = [c.value for c in ws[1]]
    need = ["№", "Ниша", "Компания", "Руководитель", "Почта (кому)", "Телефон", "Тип а/б", "Тема", "Текст письма",
            "Короткая версия для мессенджера", "Напоминание через 3 дня", "Числа из файла", "Статус"]
    miss = [h for h in need if h not in hdr]
    if miss:
        errors.append(f"нет столбцов: {miss}")
    pos = [hdr.index(h) for h in need if h in hdr]
    if pos != sorted(pos):
        errors.append("порядок обязательных столбцов нарушен")
    if ws.max_row != 31:
        errors.append(f"в xlsx {ws.max_row - 1} строк")
    if ws.freeze_panes != "D2":
        errors.append("шапка не закреплена")
    ci = {h: hdr.index(h) + 1 for h in hdr}
    for r in rows:
        row = r["n"] + 1
        if ws.cell(row, ci["Текст письма"]).value != r["letter"]:
            err(r["n"], "xlsx: текст письма отличается")
        if ws.cell(row, ci["Статус"]).value != "не отправлено":
            err(r["n"], "xlsx: статус")
        for h in ["Тема", "Короткая версия для мессенджера", "Напоминание через 3 дня", "Числа из файла", "Тип а/б"]:
            if not ws.cell(row, ci[h]).value:
                err(r["n"], f"xlsx: пусто «{h}»")
    steps = [c.value for c in wb["Как отправлять"]["A"] if isinstance(c.value, int)]
    if not 6 <= len(steps) <= 8:
        errors.append(f"шагов в «Как отправлять»: {len(steps)}")
    md = OUT_MD.read_text(encoding="utf-8")
    for f in ["разбор", "госзакуп", "[Имя]", "[Персональная", "[отрасль]", "None"]:
        if f.lower() in md.lower():
            errors.append(f"md: найдено «{f}»")
    for r in rows:
        if quote(r["letter"]) not in md:
            err(r["n"], "md: письма нет или оно отличается")
    log.append(f"8. Файлы перечитаны: xlsx — листы {wb.sheetnames}, {ws.max_row - 1} строк, обязательные столбцы "
               f"на месте и по порядку, шапка закреплена, статус «не отправлено», шагов в «Как отправлять»: {len(steps)}; "
               "md — все 30 писем есть дословно, нет «разбор», «госзакуп» и пустых подстановок.")
