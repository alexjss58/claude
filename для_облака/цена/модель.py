# ====================================================================== 4. модели
# Основной бустинг берёт только понятные признаки. Регион, код заказчика и обеспечение
# проверены отдельно (лист «Признаки»): точность они не улучшают, поэтому в модель не входят.
ПРИЗНАКИ_ОСН = ["ниша", "закон", "способ", "log_нмц", "участников"]
ПРИЗНАКИ_ДОП = ["регион_гр", "заказчик_код", "заказчик_n", "доля_обесп_контракта", "есть_обесп_заявки"]
КАТЕГОРИИ = ["ниша", "закон", "способ", "регион_гр"]
ПАРАМЕТРЫ_БУСТИНГА = dict(learning_rate=0.03, max_iter=200, max_leaf_nodes=6, min_samples_leaf=120,
                          l2_regularization=1.0)
# Параметры подобраны на трёх вариантах (сильнее/слабее регуляризация): у слабой регуляризации
# та же ошибка, но интервалы слишком узкие (покрытие p25–p75 ~43% вместо 50%).


def _регионы_топ(d, k=40):
    return list(d["Регион"].value_counts().head(k).index)


def _кодировать_заказчика(обуч: pd.DataFrame, приложить: pd.DataFrame, m: float = 5.0):
    """Сглаженное среднее падение у заказчика (по обучающей выборке).
    m — сила сглаживания к общей медиане: у заказчика с 1–2 закупками код почти равен общей медиане."""
    prior = обуч["падение"].median()
    g = обуч.groupby("инн")["падение"].agg(["sum", "count"])
    код = (g["sum"] + m * prior) / (g["count"] + m)
    x = приложить["инн"].map(код).fillna(prior).values
    n = приложить["инн"].map(g["count"]).fillna(0).values
    return x, n


def _кодировать_заказчика_oof(обуч: pd.DataFrame, k=5):
    """Тот же код, но «вне выборки» (out-of-fold), чтобы модель не подглядывала в ответ."""
    from sklearn.model_selection import GroupKFold
    x = np.zeros(len(обуч))
    n = np.zeros(len(обуч))
    for tr, te in GroupKFold(n_splits=k).split(обуч, groups=обуч["ключ"]):
        xx, nn = _кодировать_заказчика(обуч.iloc[tr], обуч.iloc[te])
        x[te] = xx
        n[te] = nn
    return x, n


def _матрица(d: pd.DataFrame, признаки: list[str], регионы=None) -> pd.DataFrame:
    X = pd.DataFrame(index=d.index)
    for c in признаки:
        if c == "регион_гр":
            X[c] = np.where(d["Регион"].isin(регионы or []), d["Регион"], "другой")
        elif c in КАТЕГОРИИ:
            X[c] = d[c]
        else:
            X[c] = d[c].astype(float)
    for c in признаки:
        if c in КАТЕГОРИИ:
            X[c] = X[c].astype(str).astype("category")
    return X


def _выровнять_категории(X_обуч, X_тест):
    for c in X_обуч.columns:
        if c in КАТЕГОРИИ:
            X_тест[c] = pd.Categorical(X_тест[c].astype(str), categories=X_обуч[c].cat.categories)
    return X_тест


class Бустинг:
    """Квантильный градиентный бустинг (sklearn HistGradientBoostingRegressor, loss='quantile'):
    отдельная модель на каждый квантиль 10/25/50/75/90%."""

    def __init__(self, с_участниками=True, доп_признаки=False, квантили=КВАНТИЛИ):
        self.признаки = [c for c in ПРИЗНАКИ_ОСН if с_участниками or c != "участников"]
        if доп_признаки:
            self.признаки += ПРИЗНАКИ_ДОП
        self.квантили = квантили
        self.модели = {}

    def _подготовить(self, d, обучение: bool):
        d = d.copy()
        if "заказчик_код" in self.признаки:
            if обучение:
                d["заказчик_код"], d["заказчик_n"] = _кодировать_заказчика_oof(d)
            else:
                d["заказчик_код"], d["заказчик_n"] = _кодировать_заказчика(self.обуч, d)
        return _матрица(d, self.признаки, self.регионы)

    def fit(self, обуч: pd.DataFrame):
        from sklearn.ensemble import HistGradientBoostingRegressor
        self.регионы = _регионы_топ(обуч)
        self.обуч = обуч
        X = self._подготовить(обуч, обучение=True)
        self.X_обуч = X
        for q in self.квантили:
            m = HistGradientBoostingRegressor(loss="quantile", quantile=q, categorical_features="from_dtype",
                                              random_state=СЛУЧАЙ, **ПАРАМЕТРЫ_БУСТИНГА)
            m.fit(X, обуч["падение"])
            self.модели[q] = m
        return self

    def матрица(self, тест):
        return _выровнять_категории(self.X_обуч, self._подготовить(тест, обучение=False))

    def predict(self, тест: pd.DataFrame) -> np.ndarray:
        X = self.матрица(тест)
        P = np.column_stack([self.модели[q].predict(X) for q in self.квантили])
        P = np.sort(P, axis=1)  # квантили не должны пересекаться
        return np.clip(P, 0, 99)


class ЛинейнаяКвантильная:
    """Простая регрессия: линейная квантильная (медианная) регрессия на понятных признаках."""

    def __init__(self, квантили=КВАНТИЛИ):
        self.квантили = квантили

    @staticmethod
    def _X(d):
        X = pd.get_dummies(d[["ниша", "закон", "способ", "корзина_участников", "корзина_нмц"]].astype(str),
                           drop_first=False, dtype=float)
        return X

    def fit(self, обуч):
        from sklearn.linear_model import QuantileRegressor
        X = self._X(обуч)
        # убираем по одной категории из каждой группы (база), чтобы коэффициенты читались
        self.база = {"ниша": "ниша_Автозапчасти", "закон": "закон_223-ФЗ", "способ": "способ_Запрос котировок",
                     "корзина_участников": "корзина_участников_1", "корзина_нмц": "корзина_нмц_до 100 тыс."}
        X = X.drop(columns=[c for c in self.база.values() if c in X.columns])
        self.cols = X.columns
        self.модели = {}
        for q in self.квантили:
            m = QuantileRegressor(quantile=q, alpha=0.0, solver="highs")
            m.fit(X.values, обуч["падение"].values)
            self.модели[q] = m
        return self

    def predict(self, тест):
        X = self._X(тест).reindex(columns=self.cols, fill_value=0.0)
        P = np.column_stack([self.модели[q].predict(X.values) for q in self.квантили])
        return np.clip(np.sort(P, axis=1), 0, 99)

    def коэффициенты(self):
        m = self.модели[0.5]
        t = pd.DataFrame({"признак": ["свободный член (база)"] + list(self.cols),
                          "влияние на медиану падения, п.п.": [m.intercept_] + list(m.coef_)})
        t["влияние на медиану падения, п.п."] = t["влияние на медиану падения, п.п."].round(1)
        return t


class ТаблицаСОткатом:
    """Квантили из самой узкой ячейки, где не меньше min_n наблюдений.
    Порядок отката: ниша+закон+способ+участники -> ниша+способ+участники -> ниша+участники
    -> участники -> ниша -> все. Так работает и JSON для сайта."""

    УРОВНИ = [["ниша", "закон", "способ", "корзина_участников"],
              ["ниша", "способ", "корзина_участников"],
              ["ниша", "корзина_участников"],
              ["корзина_участников"],
              ["ниша"],
              []]

    def __init__(self, min_n=20, квантили=КВАНТИЛИ, уровни=None):
        self.min_n = min_n
        self.квантили = квантили
        if уровни is not None:
            self.УРОВНИ = уровни

    def fit(self, обуч):
        self.табл = []
        for ур in self.УРОВНИ:
            if ур:
                g = обуч.groupby(ур, observed=True)["падение"]
                q = g.quantile(self.квантили).unstack()
                q["n"] = g.size()
                q = q[q["n"] >= self.min_n]
            else:
                q = pd.DataFrame([обуч["падение"].quantile(self.квантили).values], columns=self.квантили)
                q["n"] = len(обуч)
            self.табл.append((ур, q))
        return self

    def predict(self, тест, вернуть_уровень=False):
        P = np.full((len(тест), len(self.квантили)), np.nan)
        уровень = np.full(len(тест), "", dtype=object)
        for ур, q in self.табл:
            пусто = np.isnan(P[:, 0])
            if not пусто.any():
                break
            if ур:
                idx = pd.MultiIndex.from_frame(тест[ур].astype(object)) if len(ур) > 1 else pd.Index(тест[ур[0]].astype(object))
                qq = q.reindex(idx)
                vals = qq[self.квантили].values
            else:
                vals = np.tile(q[self.квантили].values[0], (len(тест), 1))
            ok = пусто & ~np.isnan(vals[:, 0])
            P[ok] = vals[ok]
            уровень[ok] = " + ".join(ур) if ур else "все закупки"
        return (P, уровень) if вернуть_уровень else P


class МедианаПоНише(ТаблицаСОткатом):
    """Базовая линия: медиана (и квантили) по нише."""

    def __init__(self):
        super().__init__(min_n=1, уровни=[["ниша"], []])


def метрики(y: np.ndarray, P: np.ndarray) -> dict:
    """MAE медианы, покрытие интервалов p25–p75 (цель 50%) и p10–p90 (цель 80%), ширина."""
    i10, i25, i50, i75, i90 = [КВАНТИЛИ.index(q) for q in [0.1, 0.25, 0.5, 0.75, 0.9]]
    return {
        "MAE_п.п.": round(float(np.mean(np.abs(y - P[:, i50]))), 2),
        "покрытие_p25_p75_%": round(100 * float(np.mean((y >= P[:, i25]) & (y <= P[:, i75]))), 1),
        "ширина_p25_p75_п.п.": round(float(np.mean(P[:, i75] - P[:, i25])), 1),
        "покрытие_p10_p90_%": round(100 * float(np.mean((y >= P[:, i10]) & (y <= P[:, i90]))), 1),
        "ширина_p10_p90_п.п.": round(float(np.mean(P[:, i90] - P[:, i10])), 1),
        # односторонняя калибровка: от неё зависит честность «шанса победы»
        "факт_не_выше_медианы_%": round(100 * float(np.mean(y <= P[:, i50])), 1),
        "факт_не_выше_p75_%": round(100 * float(np.mean(y <= P[:, i75])), 1),
        "n_теста": int(len(y)),
    }


def разбиения(d: pd.DataFrame):
    """Две проверки: (1) по времени — последние ~20% дат; (2) случайно 20% (по закупкам, без утечки дублей)."""
    from sklearn.model_selection import GroupShuffleSplit
    res = {}
    # (1) по времени. «Последний месяц» не годится: в нём ~85% строк, потому что
    # выгрузки упираются в потолок 1 000 строк и состоят в основном из свежих закупок.
    дни = d["дата"].sort_values()
    граница = дни.quantile(0.8)
    # тест — все дни строго после 80-го процентиля дат
    тест_мaska = d["дата"] > граница
    res["по времени"] = (np.where(~тест_мaska)[0], np.where(тест_мaska)[0],
                         f"обучение: даты окончания по {граница:%d.%m.%Y}; проверка: {граница + pd.Timedelta(days=1):%d.%m.%Y} – {d['дата'].max():%d.%m.%Y}")
    gss = GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=СЛУЧАЙ)
    tr, te = next(gss.split(d, groups=d["ключ"]))
    res["случайно 20%"] = (tr, te, "случайные 20% закупок (дубли одной закупки в разных нишах — в одной части)")
    return res


def проверить_модели(d: pd.DataFrame):
    """Обучает все модели на каждом разбиении и считает метрики. Возвращает таблицы метрик."""
    строки, по_нишам = [], []
    модели = {
        "Базовая линия: медиана по нише": lambda: МедианаПоНише(),
        "Таблица с откатом (как JSON для сайта)": lambda: ТаблицаСОткатом(min_n=20),
        "Линейная квантильная регрессия": lambda: ЛинейнаяКвантильная(),
        "Бустинг без числа участников": lambda: Бустинг(с_участниками=False),
        "Бустинг с числом участников (основная)": lambda: Бустинг(с_участниками=True),
        "Бустинг + регион, заказчик, обеспечение": lambda: Бустинг(с_участниками=True, доп_признаки=True),
    }
    описание_разбиений = {}
    for имя_р, (tr, te, опис) in разбиения(d).items():
        описание_разбиений[имя_р] = опис
        обуч, тест = d.iloc[tr], d.iloc[te]
        y = тест["падение"].values
        for имя_м, создать in модели.items():
            м = создать().fit(обуч)
            P = м.predict(тест)
            r = метрики(y, P)
            строки.append({"проверка": имя_р, "модель": имя_м, **r, "n_обучения": len(обуч)})
            for ниша in ФОКУС + ["остальные ниши"]:
                маска = (тест["ниша"] == ниша).values if ниша != "остальные ниши" else ~тест["ниша"].isin(ФОКУС).values
                if маска.sum() >= 20:
                    по_нишам.append({"проверка": имя_р, "модель": имя_м, "ниша": ниша, **метрики(y[маска], P[маска])})
            # по корзине участников — где модель хуже всего
            for кор in КОРЗИНЫ_УЧАСТНИКОВ:
                маска = (тест["корзина_участников"] == кор).values
                if маска.sum() >= 20:
                    по_нишам.append({"проверка": имя_р, "модель": имя_м, "ниша": f"участников: {кор}", **метрики(y[маска], P[маска])})
    return pd.DataFrame(строки), pd.DataFrame(по_нишам), описание_разбиений


def важность_признаков(d: pd.DataFrame) -> pd.DataFrame:
    """Насколько вырастет ошибка (MAE медианы), если перемешать признак (permutation importance).
    Модель — медианный бустинг со всеми признаками, проверка — случайные 20%."""
    from sklearn.inspection import permutation_importance
    tr, te, _ = разбиения(d)["случайно 20%"]
    м = Бустинг(с_участниками=True, доп_признаки=True, квантили=[0.5]).fit(d.iloc[tr])
    X = м.матрица(d.iloc[te])
    y = d.iloc[te]["падение"].values
    pi = permutation_importance(м.модели[0.5], X, y, scoring="neg_mean_absolute_error",
                                n_repeats=5, random_state=СЛУЧАЙ)
    имена = {"участников": "число участников", "ниша": "ниша", "регион_гр": "регион (40 частых, остальные — «другой»)",
             "заказчик_код": "история заказчика (сглаженное среднее падение)", "заказчик_n": "число закупок заказчика",
             "способ": "способ закупки", "log_нмц": "НМЦ (логарифм)", "закон": "закон",
             "доля_обесп_контракта": "обеспечение контракта, доля НМЦ", "есть_обесп_заявки": "есть обеспечение заявки"}
    t = pd.DataFrame({"признак": [имена.get(c, c) for c in X.columns],
                      "рост ошибки при перемешивании, п.п.": pi.importances_mean.round(2)})
    return t.sort_values("рост ошибки при перемешивании, п.п.", ascending=False)


# ====================================================================== 5. шанс победы (приближение)
ПОРОГИ = [5, 10, 15, 20, 25, 30, 35, 40, 50]


def шанс_по_порогам(падения: np.ndarray, пороги=ПОРОГИ) -> dict:
    """ПРИБЛИЖЕНИЕ. Доля похожих закупок, где итоговое падение победителя было не больше X.
    Читается так: «если бы вы предложили снижение X%, его хватило бы для победы примерно в Y% похожих закупок»
    — при условии, что остальные участники вели бы себя так же, а вашу заявку не отклонили."""
    падения = np.asarray(падения, dtype=float)
    return {x: round(100 * float(np.mean(падения <= x)), 0) for x in пороги}


def таблица_шансов(d: pd.DataFrame) -> pd.DataFrame:
    строки = []
    for ключи, g in d.groupby(["ниша", "закон", "способ", "корзина_участников"], observed=True):
        if len(g) < МИН_N:
            continue
        r = dict(zip(["ниша", "закон", "способ", "участников"], ключи))
        r["n"] = len(g)
        r["медиана_%"] = round(g["падение"].median(), 1)
        for x, y in шанс_по_порогам(g["падение"].values).items():
            r[f"снижение {x}% хватило бы, % закупок"] = y
        r["надёжность"] = _надёжность(len(g))
        строки.append(r)
    t = pd.DataFrame(строки)
    t["фокус"] = t["ниша"].isin(ФОКУС)
    return t.sort_values(["фокус", "ниша", "закон", "способ", "участников"], ascending=[False, True, True, True, True]).drop(columns="фокус")


