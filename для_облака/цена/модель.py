# ====================================================================== 1. загрузка
def загрузить() -> pd.DataFrame:
    """Читает все 14 файлов, добавляет нишу, код и номер файла."""
    части = []
    for путь in sorted(ПАПКА_ДАННЫХ.glob("*.xlsx")):
        m = re.search(r"\((\d+)\)", путь.name)
        номер = m.group(1) if m else "0"
        d = pd.read_excel(путь, sheet_name="Завершенные закупки", header=1)
        d = d.drop(columns=[c for c in d.columns if str(c).startswith("Unnamed")])
        ниша, код, законы = ФАЙЛЫ[номер]
        d["файл"] = номер
        d["ниша"] = ниша
        d["код"] = код
        d["выгрузка"] = законы
        части.append(d)
    df = pd.concat(части, ignore_index=True)
    for c in ["НМЦ", "Обеспечение заявки", "Обеспечение контракта", "Падения цены, %",
              "Кол-во участников", "Цена победителя"]:
        df[c] = pd.to_numeric(df[c], errors="coerce")
    df["дата"] = pd.to_datetime(df["Дата окончания"], format="%d.%m.%Y", errors="coerce")
    df["инн"] = df["ИНН Заказчика"].apply(
        lambda x: str(int(x)) if pd.notna(x) else "")
    return df


# ====================================================================== 2. очистка
def корзина_участников(x):
    if pd.isna(x):
        return np.nan
    x = int(x)
    if x <= 1:
        return "1"
    if x == 2:
        return "2"
    if x <= 4:
        return "3–4"
    return "5+"


def корзина_нмц(x):
    for lo, hi, имя in КОРЗИНЫ_НМЦ:
        if lo < x <= hi:
            return имя
    return np.nan


def очистить(df: pd.DataFrame):
    """Возвращает (основные, иной_способ, шаги_очистки, сырые_уник).

    основные      — конкурентные способы, годные для таблиц и моделей;
    иной_способ   — 223-ФЗ «Иной способ» после тех же фильтров (считается отдельно);
    шаги_очистки  — таблица «сколько строк ушло и почему»;
    сырые_уник    — уникальные закупки (после удаления дублей) до фильтра выбросов,
                    нужны для проверки чувствительности.
    """
    шаги = []

    def шаг(название, до, после, пояснение):
        шаги.append({"шаг": название, "было строк": до, "стало строк": после,
                     "убрано": до - после, "почему": пояснение})

    n0 = len(df)
    d = df[df["Закон"].notna()].copy()
    шаг("Пустые строки в конце листа", n0, len(d), "В каждом файле 2 пустые строки после таблицы.")

    d["способ"] = d["Тип проведения"].map(СПОСОБЫ).fillna("Прочие конкурентные")
    d["закон"] = d["Закон"].str.strip()

    n = len(d)
    d = d[d["способ"] != "Запрос цен"]
    шаг("«Запрос цен» (44-ФЗ)", n, len(d),
        "Это запрос цен для расчёта НМЦ, а не торги: нет ни НМЦ, ни цены победителя, ни участников.")

    # Дубликаты: одна закупка попадает и в выгрузку «44+223», и в выгрузку «223» той же ниши.
    # Ключ: предмет + ИНН заказчика + НМЦ + дата окончания + цена победителя
    # (цена победителя добавлена, чтобы не склеить разные лоты одной закупки).
    d["предмет_норм"] = (d["Предмет закупки"].astype(str).str.lower()
                         .str.replace(r"\s+", " ", regex=True).str.strip())
    d["ключ"] = (d["предмет_норм"] + "|" + d["инн"] + "|" + d["НМЦ"].round(2).astype(str)
                 + "|" + d["Дата окончания"].astype(str) + "|"
                 + d["Цена победителя"].round(2).astype(str))
    n = len(d)
    # из пары предпочитаем строку из более узкой выгрузки — они одинаковы, порядок не важен
    d = d.drop_duplicates(["ниша", "ключ"])
    шаг("Дубликаты внутри ниши", n, len(d),
        "Одна и та же закупка есть в файле «44+223» и в файле «223» одной ниши, либо повторяется внутри файла.")

    n = len(d)
    плохие_статусы = ["Размещение отменено", "Размещение не состоялось",
                      "Приостановлено определение поставщика"]
    d = d[~d["Статус"].isin(плохие_статусы)]
    шаг("Отменённые, несостоявшиеся, приостановленные", n, len(d),
        "Итоговой цены нет или она может измениться после жалобы.")

    n = len(d)
    d = d[d["Падения цены, %"].notna() & d["НМЦ"].notna() & (d["НМЦ"] > 0)]
    шаг("Нет падения цены или НМЦ", n, len(d),
        "Чаще всего ещё нет победителя («Работа комиссии») или Тендерплан не указал цену.")

    сырые_уник = d.copy()

    n = len(d)
    d = d[d["Падения цены, %"] >= 0]
    шаг("Цена победителя выше НМЦ (падение < 0)", n, len(d),
        "Цена победителя в сотни раз больше НМЦ. Похоже на закупку по цене единицы "
        "(НМЦ — сумма цен единиц, а в поле цены — объём договора). Для модели не годится.")

    n = len(d)
    d = d[d["Падения цены, %"] < ПОРОГ_ВЫБРОСА]
    шаг(f"Падение {ПОРОГ_ВЫБРОСА:.0f}% и больше", n, len(d),
        "Чаще всего «круглая» НМЦ (1, 3, 25 млн) и цена победителя в десятки тысяч: "
        "НМЦ — это максимальная сумма договора при оплате по цене единицы, либо символическая цена. "
        "Это не реальное снижение. Таких строк много в «Иной способ».")

    d["участников"] = d["Кол-во участников"].clip(upper=30)
    d["корзина_участников"] = d["Кол-во участников"].apply(корзина_участников)
    d["корзина_нмц"] = d["НМЦ"].apply(корзина_нмц)
    d["log_нмц"] = np.log10(d["НМЦ"])
    d["доля_обесп_контракта"] = (d["Обеспечение контракта"] / d["НМЦ"]).clip(0, 1).fillna(0)
    d["есть_обесп_заявки"] = d["Обеспечение заявки"].notna().astype(int)
    d["падение"] = d["Падения цены, %"]
    d["заказчик"] = d["Заказчик"].astype(str).str.strip()

    иной = d[d["способ"] == "Иной способ"].copy()
    n = len(d)
    d = d[~d["способ"].isin(["Иной способ", "Прочие конкурентные"])]
    шаг("«Иной способ» (223-ФЗ) и прочие — отдельно", n, len(d),
        "Способ по положению о закупке заказчика (электронный магазин, отбор и т. п.). "
        "Правила цены другие, выбросов много — считаем отдельной таблицей, в модель не берём. "
        "«Конкурентные переговоры» — 1 строка.")

    return d.reset_index(drop=True), иной.reset_index(drop=True), pd.DataFrame(шаги), сырые_уник


# ====================================================================== 3. таблицы
def _сводка(g: pd.Series) -> pd.Series:
    return pd.Series({
        "n": int(g.size),
        "медиана_%": round(float(g.median()), 1),
        "p25_%": round(float(g.quantile(0.25)), 1),
        "p75_%": round(float(g.quantile(0.75)), 1),
        "p10_%": round(float(g.quantile(0.10)), 1),
        "p90_%": round(float(g.quantile(0.90)), 1),
        "среднее_%": round(float(g.mean()), 1),
    })


def _надёжность(n):
    if n >= 30:
        return "достаточно данных"
    if n >= 10:
        return "мало данных — только ориентир"
    return "очень мало — не использовать"


def таблица(d: pd.DataFrame, по: list[str]) -> pd.DataFrame:
    if по:
        t = d.groupby(по, observed=True)["падение"].apply(_сводка).unstack().reset_index()
    else:
        t = _сводка(d["падение"]).to_frame().T
    t["n"] = t["n"].astype(int)
    t["надёжность"] = t["n"].apply(_надёжность)
    return t


def _порядок_уч(t):
    if "корзина_участников" in t.columns:
        t["корзина_участников"] = pd.Categorical(t["корзина_участников"], КОРЗИНЫ_УЧАСТНИКОВ, ordered=True)
    if "корзина_нмц" in t.columns:
        t["корзина_нмц"] = pd.Categorical(t["корзина_нмц"], [k[2] for k in КОРЗИНЫ_НМЦ], ordered=True)
    return t


def построить_таблицы(d: pd.DataFrame, иной: pd.DataFrame) -> dict[str, pd.DataFrame]:
    d = _порядок_уч(d.copy())
    T = {}
    T["По_нише"] = таблица(d, ["ниша"])
    T["По_закону"] = pd.concat([таблица(d, ["закон"]).assign(ниша="все ниши"),
                                таблица(d, ["ниша", "закон"])])[["ниша", "закон", "n", "медиана_%", "p25_%", "p75_%", "p10_%", "p90_%", "среднее_%", "надёжность"]]
    T["По_способу"] = pd.concat([таблица(d, ["способ"]).assign(ниша="все ниши"),
                                 таблица(d, ["ниша", "способ"])])[["ниша", "способ", "n", "медиана_%", "p25_%", "p75_%", "p10_%", "p90_%", "среднее_%", "надёжность"]]
    T["По_участникам"] = pd.concat([таблица(d, ["корзина_участников"]).assign(ниша="все ниши"),
                                    таблица(d, ["ниша", "корзина_участников"])])[["ниша", "корзина_участников", "n", "медиана_%", "p25_%", "p75_%", "p10_%", "p90_%", "среднее_%", "надёжность"]]
    T["По_НМЦ"] = pd.concat([таблица(d, ["корзина_нмц"]).assign(ниша="все ниши"),
                             таблица(d, ["ниша", "корзина_нмц"])])[["ниша", "корзина_нмц", "n", "медиана_%", "p25_%", "p75_%", "p10_%", "p90_%", "среднее_%", "надёжность"]]
    T["Ниша_закон_способ_уч"] = таблица(d, ["ниша", "закон", "способ", "корзина_участников"])

    # Крупные заказчики: >= 5 закупок в очищенных данных.
    # Одна закупка может стоять в двух нишах — для заказчиков считаем её один раз.
    дз = d.drop_duplicates("ключ")
    g = дз.groupby("инн")
    з = pd.DataFrame({
        "заказчик": g["заказчик"].first(),
        "регион": g["Регион"].first(),
        "ниши": g["ниша"].apply(lambda s: "; ".join(sorted(set(s)))),
        "законы": g["закон"].apply(lambda s: ", ".join(sorted(set(s)))),
        "n": g.size(),
        "медиана_%": g["падение"].median().round(1),
        "p25_%": g["падение"].quantile(0.25).round(1),
        "p75_%": g["падение"].quantile(0.75).round(1),
        "доля_с_1_участником_%": g["Кол-во участников"].apply(lambda s: round(100 * (s == 1).mean(), 0)),
        "медиана_участников": g["Кол-во участников"].median(),
        "сумма_НМЦ_млн": (g["НМЦ"].sum() / 1e6).round(2),
    }).reset_index().rename(columns={"инн": "ИНН"})
    з = з[з["n"] >= 5].sort_values(["n", "сумма_НМЦ_млн"], ascending=False)
    з["надёжность"] = з["n"].apply(_надёжность)
    T["Заказчики_5плюс"] = з

    иной = _порядок_уч(иной.copy())
    T["Иной_способ"] = pd.concat([
        таблица(иной, ["ниша"]).assign(корзина_участников="все"),
        таблица(иной, ["корзина_участников"]).assign(ниша="все ниши"),
        таблица(иной, ["ниша", "корзина_участников"]),
    ])[["ниша", "корзина_участников", "n", "медиана_%", "p25_%", "p75_%", "p10_%", "p90_%", "среднее_%", "надёжность"]]
    return T


def чувствительность(сырые_уник: pd.DataFrame) -> pd.DataFrame:
    """Как меняется медиана по нише при разных правилах отсечения выбросов."""
    s = сырые_уник.copy()
    s["способ"] = s["Тип проведения"].map(СПОСОБЫ)
    s = s[~s["способ"].isin(["Иной способ", "Запрос цен", "Прочие конкурентные"])]
    p = s["Падения цены, %"]
    варианты = {
        "без фильтра": p.notna(),
        "только падение >= 0": p >= 0,
        "0 <= падение < 95": (p >= 0) & (p < 95),
        "0 <= падение < 90 (принято)": (p >= 0) & (p < 90),
        "0 <= падение < 80": (p >= 0) & (p < 80),
    }
    строки = []
    for имя, маска in варианты.items():
        for ниша, g in s[маска].groupby("ниша"):
            строки.append({"правило": имя, "ниша": ниша, "n": len(g),
                           "медиана_%": round(g["Падения цены, %"].median(), 1),
                           "среднее_%": round(g["Падения цены, %"].mean(), 1)})
    t = pd.DataFrame(строки)
    w = t.pivot_table(index="ниша", columns="правило", values=["медиана_%", "среднее_%", "n"]).round(1)
    порядок = list(варианты)
    w = w.reindex(columns=pd.MultiIndex.from_product([["n", "медиана_%", "среднее_%"], порядок]))
    w.columns = [f"{a}: {b}" for a, b in w.columns]
    return w.reset_index()


