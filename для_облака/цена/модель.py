def _оформить_xlsx(путь: Path):
    from openpyxl import load_workbook
    from openpyxl.styles import Alignment, Font, PatternFill
    wb = load_workbook(путь)
    жир = Font(bold=True)
    заливка = PatternFill("solid", fgColor="EDE7D9")
    for ws in wb.worksheets:
        if ws.title == "Читать_сначала":
            ws.column_dimensions["A"].width = 130
            for row in ws.iter_rows():
                for c in row:
                    c.alignment = Alignment(wrap_text=True, vertical="top")
            ws["A1"].font = Font(bold=True, size=13)
            continue
        hdr = 1
        for c in ws[hdr]:
            c.font = жир
            c.fill = заливка
            c.alignment = Alignment(wrap_text=True, vertical="top")
        ws.freeze_panes = ws.cell(row=hdr + 1, column=1)
        from openpyxl.utils import get_column_letter
        for j in range(1, ws.max_column + 1):
            длина = max((len(str(ws.cell(row=i, column=j).value)) for i in range(1, min(ws.max_row, 200) + 1)
                         if ws.cell(row=i, column=j).value is not None), default=0)
            ws.column_dimensions[get_column_letter(j)].width = min(max(10, длина + 2), 60)
        if ws.title in ("Примеры_правил",):
            for row in ws.iter_rows(min_row=2):
                for c in row:
                    c.alignment = Alignment(wrap_text=True, vertical="top")
    wb.save(путь)


