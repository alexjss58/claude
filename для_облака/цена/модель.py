def json_для_демо(d: pd.DataFrame, иной: pd.DataFrame) -> list[dict]:
    """Формат из ПОТОКИ.md (H → F):
    [{"ниша","закон","способ","участников","медиана_снижения_%","p25_%","p75_%","n"}]
    Строки с n < МИН_N не выводим. «все» — свод по всем значениям поля
    (для способа «все» = все конкурентные способы, без «Иной способ»)."""
    строки = []

    def добавить(g, ниша, закон, способ, уч):
        if len(g) < МИН_N:
            return
        строки.append({"ниша": ниша, "закон": закон, "способ": способ, "участников": уч,
                       "медиана_снижения_%": round(float(g.median()), 1),
                       "p25_%": round(float(g.quantile(0.25)), 1),
                       "p75_%": round(float(g.quantile(0.75)), 1),
                       "n": int(len(g))})

    for ниша in sorted(d["ниша"].unique(), key=lambda x: (x not in ФОКУС, x)):
        dn = d[d["ниша"] == ниша]
        добавить(dn["падение"], ниша, "все", "все", "все")
        for кор in КОРЗИНЫ_УЧАСТНИКОВ:
            добавить(dn.loc[dn["корзина_участников"] == кор, "падение"], ниша, "все", "все", кор)
        for закон in ["44-ФЗ", "223-ФЗ"]:
            dz = dn[dn["закон"] == закон]
            добавить(dz["падение"], ниша, закон, "все", "все")
            for кор in КОРЗИНЫ_УЧАСТНИКОВ:
                добавить(dz.loc[dz["корзина_участников"] == кор, "падение"], ниша, закон, "все", кор)
            for способ in ["Электронный аукцион", "Запрос котировок", "Запрос предложений", "Открытый конкурс"]:
                ds = dz[dz["способ"] == способ]
                добавить(ds["падение"], ниша, закон, способ, "все")
                for кор in КОРЗИНЫ_УЧАСТНИКОВ:
                    добавить(ds.loc[ds["корзина_участников"] == кор, "падение"], ниша, закон, способ, кор)
        di = иной[иной["ниша"] == ниша]
        добавить(di["падение"], ниша, "223-ФЗ", "Иной способ", "все")
        for кор in КОРЗИНЫ_УЧАСТНИКОВ:
            добавить(di.loc[di["корзина_участников"] == кор, "падение"], ниша, "223-ФЗ", "Иной способ", кор)
    return строки


