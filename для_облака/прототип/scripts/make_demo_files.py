def ch(имя, условие, значение, единица="", экв=True):
    return {"имя": имя, "условие": условие, "значение": значение, "единица": единица, "эквивалент_допускается": экв}


def pos(n, наименование, окпд2, кол, ед, хар, статус, товар="", артикул="", расх=None):
    return {
        "№": n, "наименование": наименование, "ктру": "", "окпд2": окпд2, "количество": кол, "единица": ед,
        "характеристики": хар,
        "сверка": {"статус": статус, "товар_из_каталога": товар, "артикул": артикул,
                   "расхождения": [{"характеристика": a, "требуется": b, "у_товара": c} for a, b, c in (расх or [])]},
    }


def doc(номер, предмет, заказчик, закон, способ, нмц, регион, дата, позиции):
    itog = {"подходит": 0, "почти": 0, "нет": 0}
    for p in позиции:
        itog[p["сверка"]["статус"]] += 1
    return {
        "закупка": {"номер": номер, "предмет": предмет, "заказчик": заказчик, "инн_заказчика": "",
                    "закон": закон, "способ": способ, "нмц": нмц, "регион": регион, "дата_окончания": дата,
                    "ссылка": "", "источник_документа": "демо, пример: позиции техзадания составлены для показа, заказчик условный"},
        "позиции": позиции,
        "итог": itog,
        "режим": "демо",
    }


