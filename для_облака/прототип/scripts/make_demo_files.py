def write_price():
    PUBLIC.mkdir(parents=True, exist_ok=True)
    rows = [list(it) + [NOTE] for it in ITEMS]
    # CSV: разделитель «;», UTF-8 с BOM — так его правильно открывает Excel в России.
    with open(PUBLIC / "пример_прайса_оргтехники.csv", "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(HEADER)
        w.writerows(rows)

    wb = Workbook()
    ws = wb.active
    ws.title = "Прайс"
    # В XLSX сверху — пометка, шапка таблицы на 3-й строке: так видно, что разбор сам находит заголовки.
    ws["A1"] = "ПРИМЕР ПРАЙСА ОРГТЕХНИКИ (демо). Модели реальные, характеристики приблизительные — сверить с сайтом производителя. Цены условные."
    ws["A1"].font = Font(bold=True, color="A3261B")
    ws.append([])
    ws.append(HEADER)
    for c in ws[3]:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="EDE6D6")
    for r in rows:
        ws.append(r)
    widths = [10, 42, 18, 14, 26, 90, 18, 16, 12, 40]
    for i, wdt in enumerate(widths):
        ws.column_dimensions[chr(65 + i)].width = wdt
    for row in ws.iter_rows(min_row=4):
        row[5].alignment = Alignment(wrap_text=True, vertical="top")
    ws.freeze_panes = "A4"
    wb.save(PUBLIC / "пример_прайса_оргтехники.xlsx")
    # Та же таблица для встроенного примера в приложении (без сети и без сервера).
    (BASE / "src" / "data").mkdir(parents=True, exist_ok=True)
    with open(BASE / "src" / "data" / "sample_price.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(HEADER)
        w.writerows(rows)


