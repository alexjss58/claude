// Подсказка «что из ассортимента может подойти» — по названию закупки.
// Это не сверка техзадания: в демо у закупок из выгрузки нет документов, только название.

import type { CatalogItem } from '../types';

/** Категория ассортимента → слова в названии закупки, при которых она может пригодиться */
const CATEGORY_TENDER_WORDS: Record<string, RegExp> = {
  'Ноутбук': /(ноутбук|портативн\w* компьют|компьютерн\w* (техник|оборудован)|вычислительн|оргтехник)/i,
  'Системный блок': /(системн\w* блок|компьютер(?!н\w* мыш)|рабоч\w* станц|вычислительн|оргтехник)/i,
  'Моноблок': /(моноблок|компьютерн\w* (техник|оборудован)|оргтехник)/i,
  'Монитор': /(монитор|компьютерн\w* (техник|оборудован)|периферийн|оргтехник)/i,
  'МФУ': /(мфу|многофункциональн|печат|оргтехник|периферийн)/i,
  'Принтер': /(принтер|печат|оргтехник|периферийн)/i,
  'ИБП': /(ибп|бесперебойн|электропитан)/i,
  'Коммутатор': /(коммутатор|сетев\w* оборудован|сетев|скс|телекоммуникац)/i,
  'Маршрутизатор': /(маршрутизатор|сетев\w* оборудован|сетев|телекоммуникац)/i,
  'IP-телефон': /(ip-телефон|ip телефон|телефон|атс|ip-телефони)/i,
  'Телефон DECT': /(dect|беспроводн\w* трубк|радиотелефон|телефон)/i,
  'Телефон': /(телефон|атс)/i,
  'Гарнитура': /(гарнитур|наушник)/i,
  'Веб-камера': /(веб-?камер|видеоконференц|конференц)/i,
  'Проектор': /(проектор|мультимедий|интерактивн)/i,
  'Радиосистема': /(радиосистем|микрофон|звуков|звук|аудио)/i,
  'Микшерный пульт': /(микшер|пульт|звуков|звук|аудио)/i,
  'Акустическая система': /(акустич|колонк|громкоговорит|звуков|звук|аудио|оповещ)/i,
  'Телевизор': /(телевизор|телевизион|панел)/i,
  'Радиостанция': /(радиостанц|раци|радиосвяз)/i,
};

export interface MatchHint {
  count: number;
  categories: { категория: string; n: number }[];
}

export function matchHint(tenderName: string, catalog: CatalogItem[]): MatchHint {
  const cats = new Map<string, number>();
  for (const item of catalog) {
    const re = CATEGORY_TENDER_WORDS[item.категория];
    if (re && re.test(tenderName)) cats.set(item.категория, (cats.get(item.категория) || 0) + 1);
  }
  const categories = [...cats.entries()].map(([категория, n]) => ({ категория, n })).sort((a, b) => b.n - a.n);
  return { count: categories.reduce((s, c) => s + c.n, 0), categories };
}

export function findItem(catalog: CatalogItem[], артикул: string, name?: string): CatalogItem | undefined {
  return catalog.find((c) => c.артикул === артикул) || (name ? catalog.find((c) => c.наименование === name) : undefined);
}
